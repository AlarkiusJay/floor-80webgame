// Length → tier. Short phrases stay in tier 1 (teaching/early), so the
// 10–14-char "teaching tier only" rule is honored automatically.
export function cryptogramTier(len) {
  if (len <= 20) return 1;
  if (len <= 30) return 2;
  return 3;
}

export const CRYPTOGRAM_PHRASES = RAW.map((text) => ({
  text,
  tier: cryptogramTier(text.length),
}));
